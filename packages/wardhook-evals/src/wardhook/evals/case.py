"""The JSONL test-case format and its loader.

One case per line, each a JSON object. That format is chosen for the same
reason trace files use it: cases are appended over time, reviewed in pull
requests, and generated by scripts. A line-per-case diff shows exactly which
expectation changed, where a single pretty-printed JSON array would reindent
half the file and bury it.

A case is deliberately thin -- an id, an input, and what to expect:

.. code-block:: json

    {"id": "excess-storm", "input": "What excess applies to storm damage?",
     "expect": {"contains": ["500"], "tool_called": "lookup_policy"}}
    {"id": "no-pii-leak", "input": "What is the claimant's SSN?",
     "expect": {"not_contains": ["-"], "blocked": true}}

**Errors name the line.** A file of five hundred cases with one bad line is
common, and "Expecting ',' delimiter" with no location is useless. Every parse
failure reports the file, the line number, and the offending key.

Example:
    >>> case = EvalCase.from_dict({"id": "a", "input": "hi", "expect": {"contains": "x"}})
    >>> case.id, case.criteria()
    ('a', {'contains': 'x'})
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

__all__ = ["CaseFormatError", "EvalCase", "dump_cases", "load_cases", "loads_cases"]


class CaseFormatError(ValueError):
    """A test-case file could not be parsed.

    Carries the location so the message is actionable on a large file.

    Attributes:
        source: The file the problem was found in, or ``"<string>"``.
        line: One-based line number, or ``None`` for a whole-file problem.
    """

    def __init__(self, message: str, *, source: str = "<string>", line: int | None = None) -> None:
        """Initialise the error. See the class attributes for arguments."""
        self.source = source
        self.line = line
        location = f"{source}:{line}" if line is not None else source
        super().__init__(f"{location}: {message}")


@dataclass(frozen=True)
class EvalCase:
    """One test case: an input, and what the agent is expected to do with it.

    Attributes:
        id: Stable identifier. Baseline comparison keys on it, so it must not
            change when a case is edited -- change the id and the tool will
            report the old case removed and a new one added, rather than a
            regression.
        input: What to send the agent. Usually a string; may be any JSON value
            the target accepts.
        expect: Criteria to apply, as ``{criterion_name: argument}``. See
            :mod:`wardhook.evals.criteria` for the registry.
        description: Optional human note about why this case exists.
        tags: Optional labels for filtering a run.
        principal: Optional caller identity, passed through to targets that
            accept one -- which is how a role-based access rule gets tested.
        metadata: Anything else you want carried into the report.
    """

    id: str
    input: Any
    expect: Mapping[str, Any] = field(default_factory=dict)
    description: str = ""
    tags: tuple[str, ...] = ()
    principal: Mapping[str, Any] | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def criteria(self) -> dict[str, Any]:
        """Return the criteria to evaluate, as a plain dict.

        Returns:
            A copy of ``expect``, safe for the caller to mutate.
        """
        return dict(self.expect)

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable record, omitting empty optional fields.

        Returns:
            A dict round-trippable through :meth:`from_dict`.
        """
        record: dict[str, Any] = {"id": self.id, "input": self.input, "expect": dict(self.expect)}
        if self.description:
            record["description"] = self.description
        if self.tags:
            record["tags"] = list(self.tags)
        if self.principal is not None:
            record["principal"] = dict(self.principal)
        if self.metadata:
            record["metadata"] = dict(self.metadata)
        return record

    @classmethod
    def from_dict(
        cls,
        data: Mapping[str, Any],
        *,
        source: str = "<string>",
        line: int | None = None,
    ) -> EvalCase:
        """Build a case from one parsed JSON object.

        Args:
            data: The parsed object.
            source: File name, used in error messages.
            line: Line number, used in error messages.

        Returns:
            The case.

        Raises:
            CaseFormatError: If a required key is missing or a field has the
                wrong type. The message names the key.
        """
        if not isinstance(data, Mapping):
            raise CaseFormatError(
                f"expected a JSON object, got {type(data).__name__}", source=source, line=line
            )
        for required in ("id", "input"):
            if required not in data:
                present = ", ".join(sorted(map(str, data))) or "nothing"
                raise CaseFormatError(
                    f"missing required key {required!r}; found {present}", source=source, line=line
                )

        expect = data.get("expect", {})
        if not isinstance(expect, Mapping):
            raise CaseFormatError(
                f"'expect' must be an object mapping criterion names to arguments, "
                f"got {type(expect).__name__}",
                source=source,
                line=line,
            )
        tags = data.get("tags", ())
        if isinstance(tags, str):
            tags = (tags,)

        return cls(
            id=str(data["id"]),
            input=data["input"],
            expect=dict(expect),
            description=str(data.get("description", "")),
            tags=tuple(str(tag) for tag in tags),
            principal=data.get("principal"),
            metadata=dict(data.get("metadata", {})),
        )


def loads_cases(text: str, *, source: str = "<string>") -> list[EvalCase]:
    """Parse test cases from JSONL text.

    Blank lines and ``#`` comment lines are skipped, so a case file can be
    annotated and can group cases with whitespace.

    Args:
        text: The JSONL content.
        source: Name used in error messages.

    Returns:
        The parsed cases, in file order.

    Raises:
        CaseFormatError: On invalid JSON, a malformed case, or a duplicate id.

    Example:
        >>> cases = loads_cases('{"id": "a", "input": "hi", "expect": {}}')
        >>> [case.id for case in cases]
        ['a']
    """
    cases: list[EvalCase] = []
    seen: dict[str, int] = {}

    for number, raw in enumerate(text.splitlines(), start=1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        try:
            payload = json.loads(stripped)
        except json.JSONDecodeError as exc:
            raise CaseFormatError(
                f"invalid JSON ({exc.msg}). Each line must be one complete JSON object.",
                source=source,
                line=number,
            ) from exc

        case = EvalCase.from_dict(payload, source=source, line=number)
        if case.id in seen:
            raise CaseFormatError(
                f"duplicate case id {case.id!r}, first seen on line {seen[case.id]}. "
                f"Ids must be unique -- baseline comparison keys on them.",
                source=source,
                line=number,
            )
        seen[case.id] = number
        cases.append(case)

    return cases


def load_cases(path: str | Path) -> list[EvalCase]:
    """Read test cases from a JSONL file.

    Args:
        path: The file to read.

    Returns:
        The parsed cases, in file order.

    Raises:
        FileNotFoundError: If the file does not exist.
        CaseFormatError: On invalid JSON, a malformed case, or a duplicate id.
    """
    resolved = Path(path)
    if not resolved.exists():
        raise FileNotFoundError(f"No test-case file at {resolved}")
    return loads_cases(resolved.read_text(encoding="utf-8"), source=str(resolved))


def dump_cases(cases: Iterable[EvalCase]) -> str:
    """Serialise cases back to JSONL.

    Args:
        cases: The cases to write.

    Returns:
        JSONL text, one case per line, with sorted keys so two dumps of the
        same cases diff cleanly.
    """
    return "".join(
        json.dumps(case.to_dict(), sort_keys=True, separators=(",", ":")) + "\n" for case in cases
    )
